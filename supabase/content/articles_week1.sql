# Регламент вместо объяснений

Каждую передаваемую задачу опиши в коротком регламенте:

- **Результат:** как выглядит хорошо сделанная задача.
- **Шаги:** по порядку, со скриншотами, если нужно.
- **Частые ошибки** и что делать, если что-то пошло не так.
- **Срок** и куда сдавать.

Регламент пишется один раз и экономит десятки объяснений. Хорошая практика: запиши экран, пока делаешь задачу сам, и отдай видео вместе с текстом.

