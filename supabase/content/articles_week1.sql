Первая картинка работает как обложка в ленте. Она должна:

- показывать товар крупно и целиком;
- выделяться на фоне конкурентов цветом или композицией;
- нести одно главное преимущество крупным текстом.

> ! Одно преимущество на главном слайде, а не пять. Пять мелких надписей никто не прочитает.

# Слайды после главного

Хорошая последовательность для большинства товаров:

1. **Главный:** товар и ключевая выгода.
2. **Преимущества:** 3–4 пункта с иконками.
3. **Размеры и характеристики:** понятно, с цифрами.
4. **Товар в жизни:** как им пользуются.
5. **Детали:** материалы, качество, комплектация.
6. **Ответы на возражения:** что волнует покупателей в отзывах у конкурентов.

# Правила читаемости

- Крупный шрифт: карточку смотрят с телефона, текст должен читаться в маленьком превью.
- Контраст текста и фона.
- Максимум 2 шрифта и 3 цвета на карточку.
- Пиши выгоду, а не характеристику: не «хлопок 100%», а «дышит в жару, не электризуется».

# Как работать с клиентом

Перед работой попроси у селлера:

1. Ссылки на 3–5 конкурентов.
2. Главные преимущества товара по его мнению.
3. Отзывы покупателей, свои или конкурентов.

Из отзывов ты узнаешь, что реально важно покупателям. Это и надо выносить на слайды.

> Хорошая инфографика не украшает товар. Она отвечает на вопросы покупателя раньше, чем он их задал.

